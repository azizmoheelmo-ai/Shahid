/* تطبيق نموذج جاهز على هدف محدد */
function applyGoalTemplate(selectEl, elementKey, uid){
  const ti = selectEl.value;
  const card = document.getElementById('goalCard-' + uid);
  const titleEl = document.getElementById('goalTitle-' + uid);

  if(ti === ''){
    card.dataset.templateName = '';
    return;
  }
  const tpl = (PLAN_TEMPLATES[elementKey] || [])[Number(ti)];
  if(!tpl) return;

  card.querySelector('.g-perf').value = tpl.perf || '';
  card.querySelector('.g-indicators').value = (tpl.ind || []).join('\n');
  card.querySelector('.g-evidence').value = (tpl.ev || []).join('\n');
  card.querySelector('.g-actions').value = (tpl.act || []).join('\n');
  card.dataset.templateName = tpl.name;

  /* اسم الهدف يعكس اسم النموذج المطبَّق تلقائيًا — بلا أي إدخال يدوي إضافي */
  if(titleEl) titleEl.textContent = tpl.name;

  showToast('طُبِّق النموذج — عدّله بما يناسب واقعك', 'ok');
}

/* حفظ هدف واحد (إضافة أو تحديث) */
/* تحديث نص الملخص المختصر في رأس بطاقة الهدف بعد الحفظ */
function updateGoalCardSummary(uid, key, goalIdx){
  const goal = (myPlanGoals[key] || [])[goalIdx];
  const el = document.getElementById('goalSummary-' + uid);
  if(!goal || !el) return;
  const done = goal.id ? (goalShahidCounts[goal.id] || 0) : 0;
  const target = goal.target_count || 0;
  const parts = [];
  if(goal.target_level) parts.push(`مستوى ${goal.target_level}`);
  if(target > 0) parts.push(`${done}/${target} شواهد`);
  el.textContent = parts.length ? parts.join(' • ') : 'بلا تفاصيل بعد';
}

async function saveGoal(elIdx, uid){
  const row = document.getElementById('planRow-' + elIdx);
  const card = document.getElementById('goalCard-' + uid);
  const msg = document.getElementById('goalMsg-' + uid);
  const key = row.dataset.key;
  const goalIdx = Number(card.dataset.goalIdx);
  const goal = myPlanGoals[key][goalIdx];

  msg.style.color = 'var(--muted)';
  msg.textContent = 'جارٍ الحفظ...';

  try{
    const lv = card.querySelector('.g-level').value;
    const record = {
      user_id: currentUser.id,
      cycle_year: getCycleYear(),
      element_key: key,
      element_label: row.dataset.label,
      goal_order: goalIdx,
      goal_name: card.dataset.templateName || goal.template_name || '',
      target_level: lv ? Number(lv) : null,
      target_count: Number(card.querySelector('.g-count').value) || 0,
      personal_note: card.querySelector('.g-note').value.trim(),
      target_performance: card.querySelector('.g-perf').value.trim(),
      success_indicators: linesToArray(card.querySelector('.g-indicators').value),
      recommended_evidence: linesToArray(card.querySelector('.g-evidence').value),
      action_steps: linesToArray(card.querySelector('.g-actions').value),
      template_name: card.dataset.templateName || goal.template_name || ''
    };

    let savedRow;
    if(goal.id){
      const { data, error } = await sb.from('performance_goals').update(record).eq('id', goal.id).select().single();
      if(error) throw error;
      savedRow = data;
    } else {
      const { data, error } = await sb.from('performance_goals').insert(record).select().single();
      if(error) throw error;
      savedRow = data;
    }

    Object.assign(goal, {
      id: savedRow.id, goal_name: savedRow.goal_name || '', target_level: savedRow.target_level, target_count: savedRow.target_count,
      personal_note: savedRow.personal_note, target_performance: savedRow.target_performance,
      success_indicators: savedRow.success_indicators || [], recommended_evidence: savedRow.recommended_evidence || [],
      action_steps: savedRow.action_steps || [], template_name: savedRow.template_name || ''
    });

    /* تحديث myPlan المشتقة وشارات رأس البطاقة دون إعادة رسم كل شيء */
    recomputeAggregateForElement(key);
    updateElementHeaderBadges(elIdx, key);
    updateGoalCardSummary(uid, key, goalIdx);
    const titleEl = document.getElementById('goalTitle-' + uid);
    if(titleEl) titleEl.textContent = goalDisplayName(goal, goalIdx);

    msg.style.color = '#215C34';
    msg.textContent = 'تم الحفظ ✓';
    showToast('تم حفظ الهدف', 'ok');
    setTimeout(() => { if(msg.textContent === 'تم الحفظ ✓') msg.textContent = ''; }, 2500);
    refreshPlanSummary();
  } catch(err){
    msg.style.color = '#8A2C2C';
    msg.textContent = 'خطأ: ' + err.message;
  }
}

/* حذف هدف */
async function deleteGoal(elIdx, uid){
  const row = document.getElementById('planRow-' + elIdx);
  const card = document.getElementById('goalCard-' + uid);
  const key = row.dataset.key;
  const goalIdx = Number(card.dataset.goalIdx);
  const goal = myPlanGoals[key][goalIdx];

  const ok = await showConfirm('حذف هذا الهدف نهائيًا؟ الشواهد المرتبطة به تبقى محفوظة لكنها تفقد ربطها به.');
  if(!ok) return;

  try{
    if(goal.id){
      const { error } = await sb.from('performance_goals').delete().eq('id', goal.id);
      if(error) throw error;
    }
    myPlanGoals[key].splice(goalIdx, 1);
    recomputeAggregateForElement(key);

    /* إعادة رسم قائمة أهداف هذا العنصر فقط */
    const list = document.getElementById('planGoals-' + elIdx);
    list.innerHTML = myPlanGoals[key].map((g, gi) => goalCardHtml(elIdx, gi, key, row.dataset.label)).join('');
    updateElementHeaderBadges(elIdx, key);
    showToast('تم حذف الهدف', 'ok');
    refreshPlanSummary();
  } catch(err){
    showToast('تعذّر الحذف: ' + err.message, 'error');
  }
}

/* إعادة اشتقاق myPlan[key] بعد أي تعديل على أهداف عنصر معيّن */
function recomputeAggregateForElement(key){
  const goals = myPlanGoals[key] || [];
  if(!goals.length){ delete myPlan[key]; return; }
  const levels = goals.map(g => g.target_level).filter(Boolean);
  myPlan[key] = {
    target_level: levels.length ? Math.max(...levels) : null,
    target_count: goals.reduce((s, g) => s + (g.target_count || 0), 0),
    personal_note: goals.map(g => g.personal_note).filter(Boolean).join(' | '),
    target_performance: goals.map(g => g.target_performance).filter(Boolean).join(' — '),
    success_indicators: goals.flatMap(g => g.success_indicators || []),
    recommended_evidence: goals.flatMap(g => g.recommended_evidence || []),
    action_steps: goals.flatMap(g => g.action_steps || [])
  };
}

/* تحديث شارات رأس بطاقة العنصر (عدد الأهداف، أعلى مستوى، مجموع التقدم) */
function updateElementHeaderBadges(elIdx, key){
  const row = document.getElementById('planRow-' + elIdx);
  if(!row) return;
  const goals = myPlanGoals[key] || [];
  const aggTarget = goals.reduce((s, g) => s + (g.target_count || 0), 0);
  const aggDone = planShahidCounts[key] || 0;
  const isDone = aggTarget > 0 && aggDone >= aggTarget;
  const levels = goals.map(g => g.target_level).filter(Boolean);
  const topLevel = levels.length ? Math.max(...levels) : null;
  const weightBadge = row.querySelector('.plan-elem-weight').outerHTML;

  const badgesWrap = row.querySelector('.plan-row-head > div:last-child');
  badgesWrap.innerHTML = `
    ${goals.length ? `<span class="plan-badge-count" style="background:#EDF1F7;border-color:#3A5F8A;color:#2C4A72;">${goals.length} ${goals.length===1?'هدف':'أهداف'}</span>` : ''}
    ${topLevel ? `<span class="plan-badge-level">${topLevel}</span>` : ''}
    ${aggTarget > 0 ? `<span class="plan-badge-count ${isDone ? 'done' : ''}">${aggDone}/${aggTarget}</span>` : ''}
    ${weightBadge}`;
}

